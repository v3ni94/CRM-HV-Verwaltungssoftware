def ticket_context(ticket: Ticket, *, now: datetime | None = None) -> dict[str, Any]:
    """Ticket fields plus derived condition fields (M9-08): ``age_days`` (whole days since
    creation) and ``due_in_days`` (whole days until ``sla_due_at``, negative once overdue),
    so a rule condition can read ``entity.age_days`` (Ticketalter) or ``entity.due_in_days``
    (Fristbezug, Tage vor Termin) with the existing ``gt``/``lt`` operators. ``None`` when
    the ticket has no deadline."""
    context = {k: normalise(getattr(ticket, k)) for k in TICKET_CONTEXT_FIELDS}
    now = now or datetime.now(UTC)
    context["age_days"] = (now - ticket.created_at).days
    context["due_in_days"] = (
        (ticket.sla_due_at - now).days if ticket.sla_due_at is not None else None
    )
    return context


async def message_context(session: AsyncSession, message: Any) -> dict[str, Any]:
    """Fields of a mail for rule conditions (Lern-Workflow, rule M9-11): sender address and
    domain in lower case, assignment fields, the ticket of the mail and ``opens_ticket`` (the
    mail is the first inbound mail of its ticket, i.e. the ticket was opened by it; a reply
    joining an existing ticket is not)."""
    from mhvp.communication.models import Message

    address = (message.from_address or "").strip().lower() or None
    opens_ticket = False
    if message.ticket_id is not None and message.direction == "in":
        first = await session.scalar(
            select(Message.id)
            .where(Message.ticket_id == message.ticket_id, Message.direction == "in")
            .order_by(Message.created_at, Message.id)
            .limit(1)
        )
        opens_ticket = first == message.id
    return {
        "id": str(message.id),
        "direction": message.direction,
        "from_address": address,
        "from_domain": address.rsplit("@", 1)[1] if address and "@" in address else None,
        "mailbox_id": normalise(message.mailbox_id),
        "contact_id": normalise(message.contact_id),
        "property_id": normalise(message.property_id),
        "ticket_id": normalise(message.ticket_id),
        "opens_ticket": opens_ticket,
        "subject": message.subject,
    }


async def build_context(
    session: AsyncSession,
    *,
    type: str,
    entity_type: str,
    entity_id: uuid.UUID | None,
    payload: dict[str, Any] | None,
    actor_user_id: uuid.UUID | None = None,
    entity_override: dict[str, Any] | None = None,
    related: set[str] | None = None,
    tenant_id: uuid.UUID | None = None,
) -> dict[str, Any]:
    """Evaluation context: event fields plus the current fields of a ticket entity and, for
    the groups in ``related`` (A81), the linked property, unit, contact and contract."""
    entity: dict[str, Any] = dict(entity_override or {})
    if entity_type == "ticket" and entity_id is not None and not entity_override:
        ticket = await session.get(Ticket, entity_id)
        if ticket is not None:
            entity = ticket_context(ticket)
    elif entity_type == "message" and entity_id is not None and not entity_override:
        from mhvp.communication.models import Message

        message = await session.get(Message, entity_id)
        if message is not None:
            entity = await message_context(session, message)
    context = {
        "type": type,
        "entity_type": entity_type,
        "entity_id": str(entity_id) if entity_id else None,
        "actor_user_id": str(actor_user_id) if actor_user_id else None,
        "payload": {k: normalise(v) for k, v in (payload or {}).items()},
        "entity": entity,
    }
    if related:
        await enrich_context(session, context, related, tenant_id=tenant_id)
    return context


async def context_for_event(
    session: AsyncSession, event: DomainEvent, related: set[str] | None = None
) -> dict[str, Any]:
    return await build_context(
        session,
        type=event.type,
        entity_type=event.entity_type,
        entity_id=event.entity_id,
        payload=event.payload,
        actor_user_id=event.actor_user_id,
        related=related,
        tenant_id=event.tenant_id,
    )


# --- related master data (A81) ------------------------------------------------------------


def _id_from(context: dict[str, Any], *paths: str) -> uuid.UUID | None:
    """First UUID found at ``paths`` in the entity, the payload or the event itself."""
    for path in paths:
        source, _, key = path.partition(".")
        value = (context.get(source) or {}).get(key) if source else context.get(key)
        if value in (None, ""):
            continue
        try:
            return uuid.UUID(str(value))
        except ValueError:
            continue
    return None


def _pick(row: Any, fields: tuple[str, ...]) -> dict[str, Any]:
    return {k: normalise(getattr(row, k, None)) for k in fields}


def contract_status(start: date, end: date | None, termination: date | None, today: date) -> str:
    """Derived status of a contract at ``today`` (deterministic, no stored field)."""
    if start > today:
        return "future"
    if end is not None and end < today:
        return "ended"
    if termination is not None:
        return "terminated"
    return "active"


async def enrich_context(
    session: AsyncSession,
    context: dict[str, Any],
    groups: set[str],
    *,
    tenant_id: uuid.UUID | None = None,
    today: date | None = None,
) -> dict[str, Any]:
    """Add ``property``, ``unit``, ``contact`` and ``contract`` (only the requested groups)
    to the context from the ids of the entity or the payload. One query per group; a missing
    link yields an empty group so every field resolves to ``None``. Rows of another tenant
    are never read (RLS plus an explicit tenant filter)."""
    from mhvp.contacts.models import Contact, ContactTag, ContactTagLink, PartyMember
    from mhvp.contracts.models import Contract
    from mhvp.properties.models import Property, Unit

    def scoped(query: Any, model: Any) -> Any:
        return query.where(model.tenant_id == tenant_id) if tenant_id is not None else query

    for group in groups:
        if group in RELATED_FIELDS:
            context.setdefault(group, {})
    entity_type = context.get("entity_type")
    property_id = _id_from(
        context,
        "entity.property_id",
        "payload.property_id",
        *(("entity_id",) if entity_type == "property" else ()),
    )
    unit_id = _id_from(
        context,
        "entity.unit_id",
        "payload.unit_id",
        *(("entity_id",) if entity_type == "unit" else ()),
    )
    contact_id = _id_from(
        context,
        "entity.contact_id",
        "entity.initiator_contact_id",
        "payload.contact_id",
        *(("entity_id",) if entity_type == "contact" else ()),
    )
    unit: Unit | None = None
    if ("unit" in groups or "contract" in groups) and unit_id is not None:
        unit = await session.scalar(scoped(select(Unit).where(Unit.id == unit_id), Unit))
        if unit is not None and property_id is None:
            property_id = unit.property_id
    if "unit" in groups and unit is not None:
        context["unit"] = _pick(unit, RELATED_FIELDS["unit"])
    if "property" in groups and property_id is not None:
        prop = await session.scalar(
            scoped(select(Property).where(Property.id == property_id), Property)
        )
        if prop is not None:
            context["property"] = _pick(prop, RELATED_FIELDS["property"])
    if "contact" in groups and contact_id is not None:
        contact = await session.scalar(
            scoped(select(Contact).where(Contact.id == contact_id), Contact)
        )
        if contact is not None:
            tags = list(
                await session.scalars(
                    scoped(
                        select(ContactTag.name)
                        .join(ContactTagLink, ContactTagLink.tag_id == ContactTag.id)
                        .where(ContactTagLink.contact_id == contact.id)
                        .order_by(ContactTag.name),
                        ContactTagLink,
                    )
                )
            )
            data = _pick(contact, RELATED_FIELDS["contact"])
            data["roles"] = sorted(str(normalise(r)) for r in (contact.roles or []))
            data["tags"] = tags
            context["contact"] = data
    if "contract" in groups and unit_id is not None:
        today = today or datetime.now(SCHEDULE_TZ).date()
        rows = list(
            await session.scalars(
                scoped(select(Contract).where(Contract.unit_id == unit_id), Contract).order_by(
                    Contract.start_date.desc(), Contract.id
                )
            )
        )
        own_parties: set[uuid.UUID] = set()
        if rows and contact_id is not None:
            own_parties = set(
                await session.scalars(
                    scoped(
                        select(PartyMember.party_id).where(
                            PartyMember.contact_id == contact_id,
                            PartyMember.party_id.in_([r.party_id for r in rows]),
                        ),
                        PartyMember,
                    )
                )
            )

        def rank(row: Contract) -> tuple[int, int, int, int, str]:
            status = contract_status(row.start_date, row.end_date, row.termination_date, today)
            return (
                0 if row.party_id in own_parties else 1,
                0 if status in ("active", "terminated") else 1,
                0 if str(normalise(row.kind)) == "tenancy" else 1,
                # Latest start first, then the id, so the choice is stable.
                -row.start_date.toordinal(),
                str(row.id),
            )

        if rows:
            best = min(rows, key=rank)
            data = _pick(best, RELATED_FIELDS["contract"])
            data["status"] = contract_status(
                best.start_date, best.end_date, best.termination_date, today
            )
            context["contract"] = data
    return context


def related_for_rules(rules: list[AutomationRule]) -> set[str]:
    """Union of the related groups the condition trees of ``rules`` read."""
    groups: set[str] = set()
    for rule in rules:
        groups |= related_groups(rule.conditions)
    return groups


