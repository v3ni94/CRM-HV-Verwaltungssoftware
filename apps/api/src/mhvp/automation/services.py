def schedule_context(rule: AutomationRule, due: datetime) -> dict[str, Any]:
    return {
        "type": SCHEDULE_EVENT_TYPE,
        "entity_type": "schedule",
        "entity_id": None,
        "actor_user_id": None,
        "payload": {
            "due_at": due.astimezone(UTC).isoformat(),
            "frequency": (rule.schedule or {}).get("frequency"),
            "rule_name": rule.name,
        },
        "entity": {},
    }


async def process_schedules(
    session: AsyncSession,
    tenant_id: uuid.UUID,
    *,
    now: datetime,
    settings: Settings | None = None,
) -> dict[str, int]:
    """Run every active schedule rule whose latest due moment is newer than its watermark.
    The first pass of a rule only positions the watermark (moments before activation are
    history); the run id is derived from rule and due moment, so a concurrent worker cannot
    run the same window twice."""
    totals = {"runs": 0, "failed": 0}
    rules = list(
        await session.scalars(
            select(AutomationRule)
            .where(
                AutomationRule.tenant_id == tenant_id,
                AutomationRule.active.is_(True),
                AutomationRule.trigger_kind == TRIGGER_SCHEDULE,
            )
            .order_by(AutomationRule.created_at, AutomationRule.id)
        )
    )
    for rule in rules:
        if not rule.schedule:
            continue
        if rule.last_scheduled_at is None:
            rule.last_scheduled_at = now
            continue
        due = previous_due(rule.schedule, now)
        if due <= rule.last_scheduled_at:
            continue
        event = DomainEvent(
            id=window_event_id(rule.id, due),
            tenant_id=tenant_id,
            type=SCHEDULE_EVENT_TYPE,
            entity_type="schedule",
            entity_id=None,
            actor_user_id=None,
            occurred_at=due,
            payload={},
        )
        run = await _run_rule(
            session,
            tenant_id=tenant_id,
            rule=rule,
            event=event,
            context=schedule_context(rule, due),
            settings=settings,
            now=now,
        )
        rule.last_scheduled_at = due
        if run is None:
            continue
        totals["runs"] += 1
        if run.status == RUN_STATUS_FAILED:
            totals["failed"] += 1
    return totals


# --- processing ---------------------------------------------------------------------------


async def _run_rule(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID,
    rule: AutomationRule,
    event: DomainEvent,
    context: dict[str, Any] | None = None,
    settings: Settings | None = None,
    now: datetime | None = None,
) -> AutomationRun | None:
    """Execute one rule for one event, idempotent. ``None`` when already run or no match.
    ``event`` may be a transient schedule window (not persisted, see ``process_schedules``)."""
    existing = await session.scalar(
        select(AutomationRun.id).where(
            AutomationRun.rule_id == rule.id, AutomationRun.event_id == event.id
        )
    )
    if existing is not None:
        return None
    if context is None:
        context = await context_for_event(session, event)
    try:
        if not evaluate(rule.conditions, context):
            return None
    except Exception as exc:  # invalid stored tree: record and continue
        return await _record(session, tenant_id, rule, event, RUN_STATUS_FAILED, [], str(exc))
    try:
        async with session.begin_nested():
            actions = await execute_actions(
                session,
                tenant_id=tenant_id,
                rule=rule,
                event_id=event.id,
                context=context,
                dry_run=False,
                settings=settings,
            )
            run = await _record(
                session, tenant_id, rule, event, RUN_STATUS_EXECUTED, actions, None, now=now
            )
        return run
    except IntegrityError:
        # Concurrent worker already recorded this rule and event (unique constraint).
        return None
    except Exception as exc:
        log.warning(
            "automation rule failed",
            extra={"tenant_id": str(tenant_id), "rule_id": str(rule.id), "event_id": str(event.id)},
        )
        return await _record(
            session, tenant_id, rule, event, RUN_STATUS_FAILED, [], str(exc)[:2000]
        )


async def _record(
    session: AsyncSession,
    tenant_id: uuid.UUID,
    rule: AutomationRule,
    event: DomainEvent,
    status: str,
    actions: list[dict[str, Any]],
    error: str | None,
    now: datetime | None = None,
) -> AutomationRun:
    """Write the run; webhook actions hand their payload to the outbox (A82), due at ``now``
    (the beat moment, so that the delivery step of the same pass sends it)."""
    now = now or datetime.now(UTC)
    pending = [(a.pop(PENDING_DELIVERY_KEY), a) for a in actions if PENDING_DELIVERY_KEY in a]
    run = AutomationRun(
        tenant_id=tenant_id,
        rule_id=rule.id,
        event_id=event.id,
        event_type=event.type,
        status=status,
        error=error,
        # Copy: the delivery ids are added below, and the JSONB column only writes a changed
        # value when the new list differs from the one inserted here.
        actions=[dict(a) for a in actions],
        finished_at=now,
    )
    session.add(run)
    await session.flush()
    for spec, result in pending:
        delivery = AutomationWebhookDelivery(
            tenant_id=tenant_id, run_id=run.id, rule_id=rule.id, next_attempt_at=now, **spec
        )
        session.add(delivery)
        await session.flush()
        # Stable across every retry of this row (M9-08); the id already is, this makes the
        # intent explicit for receivers keying on ``Idempotency-Key`` instead.
        delivery.idempotency_key = str(delivery.id)
        result["delivery_id"] = str(delivery.id)
    if pending:
        run.actions = [dict(a) for a in actions]
        await session.flush()
    return run


async def process_tenant(
    session: AsyncSession,
    tenant_id: uuid.UUID,
    *,
    now: datetime | None = None,
    settings: Settings | None = None,
) -> dict[str, int]:
    """Process new events of one tenant since its watermark (see module docstring), then
    send the due webhook deliveries of the tenant (A82)."""
    now = now or datetime.now(UTC)
    settings = settings or get_settings()
    totals = {"events": 0, "runs": 0, "failed": 0, "webhooks": 0, "webhooks_failed": 0}
    scheduled = await process_schedules(session, tenant_id, now=now, settings=settings)
    totals["runs"] += scheduled["runs"]
    totals["failed"] += scheduled["failed"]
    await _process_events(session, tenant_id, now=now, settings=settings, totals=totals)
    delivered = await deliver_due_webhooks(session, tenant_id, now=now, settings=settings)
    totals["webhooks"] += delivered["webhooks"]
    totals["webhooks_failed"] += delivered["webhooks_failed"]
    return totals


async def _process_events(
    session: AsyncSession,
    tenant_id: uuid.UUID,
    *,
    now: datetime,
    settings: Settings,
    totals: dict[str, int],
) -> None:
    cutoff = now - PROCESS_LAG
    watermark = await session.scalar(
        select(AutomationWatermark).where(AutomationWatermark.tenant_id == tenant_id)
    )
    if watermark is None:
        # First run: start at the current cut-off; older events are history, not triggers.
        watermark = AutomationWatermark(
            tenant_id=tenant_id, last_occurred_at=cutoff, last_event_id=None
        )
        session.add(watermark)
        await session.flush()
        return
    rules = list(
        await session.scalars(
            select(AutomationRule)
            .where(
                AutomationRule.tenant_id == tenant_id,
                AutomationRule.active.is_(True),
                AutomationRule.trigger_kind != TRIGGER_SCHEDULE,
            )
            .order_by(AutomationRule.created_at, AutomationRule.id)
        )
    )
    by_type: dict[str, list[AutomationRule]] = {}
    for rule in rules:
        if rule.trigger_event_type:
            by_type.setdefault(rule.trigger_event_type, []).append(rule)
    query = (
        select(DomainEvent)
        .where(DomainEvent.tenant_id == tenant_id, DomainEvent.occurred_at <= cutoff)
        .order_by(DomainEvent.occurred_at, DomainEvent.id)
        .limit(BATCH_LIMIT)
    )
    if watermark.last_occurred_at is not None:
        last_at, last_id = watermark.last_occurred_at, watermark.last_event_id
        if last_id is None:
            query = query.where(DomainEvent.occurred_at > last_at)
        else:
            query = query.where(
                (DomainEvent.occurred_at > last_at)
                | ((DomainEvent.occurred_at == last_at) & (DomainEvent.id > last_id))
            )
    events = list(await session.scalars(query))
    for event in events:
        totals["events"] += 1
        if is_automation_event(event.payload):
            continue
        matching = by_type.get(event.type, [])
        if not matching:
            continue
        # One context per event: related data (A81) is loaded once for every rule of the type.
        context = await context_for_event(session, event, related=related_for_rules(matching))
        for rule in matching:
            run = await _run_rule(
                session,
                tenant_id=tenant_id,
                rule=rule,
                event=event,
                context=context,
                settings=settings,
                now=now,
            )
            if run is None:
                continue
            totals["runs"] += 1
            if run.status == RUN_STATUS_FAILED:
                totals["failed"] += 1
    if events:
        watermark.last_occurred_at = events[-1].occurred_at
        watermark.last_event_id = events[-1].id
    watermark.updated_at = now
