async def execute_actions(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID,
    rule: AutomationRule,
    event_id: uuid.UUID,
    context: dict[str, Any],
    dry_run: bool,
    settings: Settings | None = None,
) -> list[dict[str, Any]]:
    """Run the rule's actions in order. Raises ``ActionError`` on the first failing action
    (the caller rolls back the savepoint and records the failure)."""
    settings = settings or get_settings()
    results: list[dict[str, Any]] = []
    for index, action in enumerate(parse_actions(rule.actions, stored=True)):
        results.append(
            await _execute_one(
                session,
                tenant_id=tenant_id,
                rule=rule,
                event_id=event_id,
                action=action,
                action_index=index,
                context=context,
                dry_run=dry_run,
                settings=settings,
            )
        )
    return results


async def _execute_one(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID,
    rule: AutomationRule,
    event_id: uuid.UUID,
    action: Action,
    action_index: int,
    context: dict[str, Any],
    dry_run: bool,
    settings: Settings,
) -> dict[str, Any]:
    if isinstance(action, CreateTicketAction):
        return await _create_ticket(
            session,
            tenant_id=tenant_id,
            rule=rule,
            event_id=event_id,
            action=action,
            context=context,
            dry_run=dry_run,
        )
    if isinstance(action, NotifyAction):
        return await _notify(
            session, tenant_id=tenant_id, rule=rule, action=action, context=context, dry_run=dry_run
        )
    if isinstance(action, WebhookAction):
        return await _webhook(
            rule=rule,
            action=action,
            action_index=action_index,
            context=context,
            dry_run=dry_run,
            settings=settings,
        )
    if isinstance(action, MailDraftAction):
        return await _mail_draft(
            session, tenant_id=tenant_id, rule=rule, action=action, context=context, dry_run=dry_run
        )
    if isinstance(action, LetterDraftAction):
        return await _letter_draft(
            session,
            tenant_id=tenant_id,
            rule=rule,
            event_id=event_id,
            action=action,
            context=context,
            dry_run=dry_run,
            settings=settings,
        )
    if isinstance(action, AiTaskAction):
        return await _ai_task(
            session,
            tenant_id=tenant_id,
            rule=rule,
            action=action,
            context=context,
            dry_run=dry_run,
            settings=settings,
        )
    if isinstance(action, AssignRecordAction):
        return await _assign_record(
            session,
            tenant_id=tenant_id,
            rule=rule,
            event_id=event_id,
            action=action,
            context=context,
            dry_run=dry_run,
        )
    if isinstance(action, CreateTaskAction):
        return await _create_task(
            session,
            tenant_id=tenant_id,
            rule=rule,
            event_id=event_id,
            action=action,
            context=context,
            dry_run=dry_run,
        )
    return await _set_ticket_field(
        session,
        tenant_id=tenant_id,
        rule=rule,
        event_id=event_id,
        action=action,
        context=context,
        dry_run=dry_run,
    )


# --- dry run ------------------------------------------------------------------------------


async def dry_run(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID,
    rule: AutomationRule,
    context: dict[str, Any],
    settings: Settings | None = None,
) -> dict[str, Any]:
    """Evaluate a rule against a sample context without any effect (no run is recorded)."""
    if rule.trigger_kind == TRIGGER_SCHEDULE:
        trigger_matches = context.get("type") == SCHEDULE_EVENT_TYPE
    else:
        trigger_matches = context.get("type") == rule.trigger_event_type
    matched = trigger_matches and evaluate(rule.conditions, context)
    actions: list[dict[str, Any]] = []
    error: str | None = None
    if matched:
        try:
            # dry_run=True: every action returns its preview before any write.
            actions = await execute_actions(
                session,
                tenant_id=tenant_id,
                rule=rule,
                event_id=uuid.uuid4(),
                context=context,
                dry_run=True,
                settings=settings,
            )
        except ActionError as exc:
            error = str(exc)
    return {
        "status": RUN_STATUS_DRY_RUN,
        "trigger_matches": trigger_matches,
        "matched": bool(matched),
        "actions": actions,
        "error": error,
        "context": context,
    }


